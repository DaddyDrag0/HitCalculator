const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const data=JSON.parse(fs.readFileSync('relic-upgrades.json','utf8'))
assert.equal(data.relics.length,8)
assert.deepEqual(data.grades,['Base','Platinum','Crystal','Ruby','Galaxy'])
assert.equal(data.relics.reduce((n,r)=>n+r.recipes.length,0),32)
for(const r of data.relics){assert.equal(r.values.length,5);assert.equal(r.recipes.length,4)}
const settings=fs.readFileSync('relic-upgrades-v1.js','utf8')
const app=fs.readFileSync('app.js','utf8')
const rolls=fs.readFileSync('roll-simulator-v15.js','utf8')
const direct=fs.readFileSync('upgrade-v2.js','utf8')
const probability=fs.readFileSync('vicissitudes-v14.js','utf8')
const quick=fs.readFileSync('roll-sim-worker-v39.js','utf8')
const advanced=fs.readFileSync('roll-sim-worker-v30.js','utf8')
const html=fs.readFileSync('relics.html','utf8')
assert.match(app,/relic-upgrades-v1\.js/)
assert.match(html,/relic-planner\.js/)
assert.match(settings,/hitcalc-relic-upgrade-levels-v1/)
assert.match(rolls,/relicLevels: window\.HIT_RELIC_LEVELS/)
assert.match(direct,/relicValue\('Quickdraw',10\)/)
assert.match(direct,/relicValue\('HeavyHand',20\)/)
assert.match(probability,/relicValue\('Vicissitudes',10\)/)
assert.match(probability,/relicValue\('LuckySurge',25\)/)
assert.match(probability,/relicValue\('TheDice',100\)/)
assert.match(advanced,/relicVicFactorsV43\(build,vicIndex\)/)
assert.match(quick,/makeCardDistribution\(build, weather, group\.surge, group\.dice/)
assert.ok(!settings.includes('CardRngExpansionDepths/relics.html'),'Planner moved onto HitCalc')
const ctx=vm.createContext({self:{},importScripts:()=>{},console})
vm.runInContext(fs.readFileSync('roll-sim-data-v16.js','utf8'),ctx)
vm.runInContext(fs.readFileSync('roll-sim-worker-v16.js','utf8'),ctx)
const evalWorker=x=>vm.runInContext(x,ctx)
assert.equal(evalWorker("relicRollBoostV43({modifiers:{relicLevels:{Quickdraw:0}}},'Quickdraw',[10,15,20,25,30])"),10)
assert.equal(evalWorker("relicRollBoostV43({modifiers:{relicLevels:{Quickdraw:4}}},'Quickdraw',[10,15,20,25,30])"),30)
assert.equal(evalWorker("relicRollBoostV43({modifiers:{relicLevels:{LuckySurge:4}}},'LuckySurge',[25,30,35,40,50])"),50)
assert.equal(evalWorker("relicRollBoostV43({modifiers:{relicLevels:{TheDice:4}}},'TheDice',[100,125,175,225,300])"),300)
const build=JSON.stringify({rolls:0,charm:'None',modifiers:{quickdraw:true,heavyHand:true,relicLevels:{Quickdraw:4,HeavyHand:4}}})
const baseBuild=JSON.stringify({rolls:0,charm:'None',modifiers:{quickdraw:true,heavyHand:true,relicLevels:{Quickdraw:0,HeavyHand:0}}})
assert.ok(evalWorker('baseLuck('+build+',null,false)')>evalWorker('baseLuck('+baseBuild+',null,false)'))
assert.ok(evalWorker('rollsPerSecond('+build+',null)')>evalWorker('rollsPerSecond('+baseBuild+',null)'))
const factors=evalWorker("relicVicFactorsV43({modifiers:{relicLevels:{Vicissitudes:4}}},0)")
assert.equal(factors[0],1.3)
assert.equal(factors[1],0.9)
console.log('Relic grades, planner, and actual v16 rolling worker tier effects pass.')
